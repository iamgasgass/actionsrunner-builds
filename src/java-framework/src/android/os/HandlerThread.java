package android.os;

public class HandlerThread extends Thread {
    private Looper mLooper;
    private Handler mHandler;
    private final int mPriority;
    private volatile int mTid = -1;
    public HandlerThread(String name) { this(name, Process.THREAD_PRIORITY_DEFAULT); }
    public HandlerThread(String name, int priority) { super(name); mPriority = priority; }
    protected void onLooperPrepared() {}
    @Override public void run() {
        mTid = Process.myTid();
        Looper.prepare();
        synchronized (this) { mLooper = Looper.myLooper(); notifyAll(); }
        onLooperPrepared();
        Looper.loop();
        mTid = -1;
    }
    /** As Android's: null when the thread was never started or has ended (it used to wait for ever then). */
    public Looper getLooper() {
        if (!isAlive()) return mLooper;
        boolean interrupted = false;
        synchronized (this) {
            while (isAlive() && mLooper == null) {
                try { wait(50); } catch (InterruptedException e) { interrupted = true; }
            }
        }
        if (interrupted) Thread.currentThread().interrupt();
        return mLooper;
    }
    public boolean quit() { Looper l = getLooper(); if (l != null) { l.quit(); return true; } return false; }
    public boolean quitSafely() { Looper l = getLooper(); if (l != null) { l.quitSafely(); return true; } return false; }
    public java.util.concurrent.Executor getThreadExecutor() { final Handler h = getThreadHandler(); return h == null ? null : (r -> h.post(r)); }
    public android.os.Handler getThreadHandler() { synchronized (this) { if (mHandler == null && getLooper() != null) mHandler = new Handler(getLooper()); return mHandler; } }
    public int getThreadId() { return mTid; }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    protected void onCreated() {}
    // ---- end of generated members
}
